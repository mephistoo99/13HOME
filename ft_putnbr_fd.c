#include "libft.h"

static void	print_nb(long nb, int fd)
{
	if (nb >= 10)
		print_nb(nb / 10, fd);
	ft_putchar_fd((nb % 10) + '0', fd);
}

void	ft_putnbr_fd(int n, int fd)
{
	long	nb;

	if (fd < 0)
		return ;
	nb = n;
	if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		nb = -nb;
	}
	print_nb(nb, fd);
}
