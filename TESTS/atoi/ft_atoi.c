int ft_atoi(const char *s)
{
    int nbr;
    int sign;

    nbr = 0;
    sign = 1;
    while (*s == ' ' || (*s >= 9 && *s <= 13))
		s++;
    if (*s == '+' || *s == '-')
	{
		if (*s == '-')
			sign *= -1;
		s++;
	}
    while (*s >= '0' && *s <= '9')
	{
		nbr = (nbr * 10) + (*s - '0');
		s++;
	}
	return (sign * nbr);
}
