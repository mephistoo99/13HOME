#include "libft.h"

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*ptr;
	char	*ptr2;
	size_t	s_len;

	if (!s)
	{
		return (NULL);
	}
	s_len = ft_strlen(s);
	if (start >= s_len)
		len = 0;
	else if (len > s_len - start)
		len = s_len - start;
	ptr = (char *)s + start;
	ptr2 = malloc(len + 1);
	if (!ptr2)
		return (NULL);
	ft_memcpy(ptr2, ptr, len);
	ptr2[len] = '\0';
	return (ptr2);
}
